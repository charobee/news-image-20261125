#!/usr/bin/env python3
"""make.fun entry: Sum up 25 November's world news in one image.

Writes the pre-built image to /output/entry.png. Deterministic: a plain
byte-for-byte copy of the bundled entry.png (no network, no clock, no
randomness), so repeated runs produce identical bytes.

The image itself is generated by build_image.py (Pillow, system fonts only);
it is bundled here so the program is self-contained and reproducible.
"""
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "entry.png")
DST = os.environ.get("MAKEFUN_OUTPUT", "/output/entry.png")


def main():
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    shutil.copyfile(SRC, DST)
    print(f"wrote {DST} ({os.path.getsize(DST)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
